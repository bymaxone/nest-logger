/**
 * @fileoverview Generates `src/server/utils/glyph-letters.generated.ts`: the symbols that are drawn as a
 * Latin letter and that Unicode gives no decomposition for (the negative circled and the negative
 * squared letters, the regional indicators), by the letter their name ends in.
 *
 * The input is `scripts/unicode/latin-letter-names.txt`, the lines of the Unicode Character Database's
 * `UnicodeData.txt` (version below) whose name ends in `LATIN CAPITAL LETTER X`, `LATIN SMALL LETTER X` or
 * `REGIONAL INDICATOR SYMBOL LETTER X`:
 *
 *   grep -E '(LATIN (CAPITAL|SMALL) LETTER|REGIONAL INDICATOR SYMBOL LETTER) [A-Z];' UnicodeData.txt
 *
 * A line is kept when its general category is `So` (a symbol: a letter or a mark is read by the fold
 * already) and its decomposition field is empty (a symbol that decomposes is read by the compatibility
 * form). The tag letters (`TAG LATIN ...`, category `Cf`) and the combining small letters (category `Mn`)
 * are left out: they print as nothing or as a mark, and the fold drops them. Usage: `node scripts/generate-glyph-letters.mjs` writes the file; `--print` prints it.
 *
 * @layer scripts
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const INPUT = join(root, 'scripts/unicode/latin-letter-names.txt')
const OUTPUT = join(root, 'src/server/utils/glyph-letters.generated.ts')
const NAME_END = /(?:LATIN (?:CAPITAL|SMALL) LETTER|REGIONAL INDICATOR SYMBOL LETTER) ([A-Z])$/

/**
 * The generated module for the lines of `UnicodeData.txt` given.
 *
 * @param {string} text - Lines of `UnicodeData.txt`.
 * @returns {string} The source of the generated module.
 */
export function generate(text) {
  const glyphs = []
  for (const line of text.split('\n')) {
    const [code, name, category, , , decomposition] = line.split(';')
    const letter = NAME_END.exec(name ?? '')?.[1]
    if (letter === undefined || category !== 'So' || decomposition !== '') continue
    glyphs.push([Number.parseInt(code, 16), letter.toLowerCase()])
  }
  glyphs.sort((a, b) => a[0] - b[0])
  const runs = []
  for (const [code, letter] of glyphs) {
    const last = runs.at(-1)
    if (last !== undefined && last[0] + last[1].length === code) last[1] += letter
    else runs.push([code, letter])
  }
  const rows = runs.map(([code, letters]) => `  [0x${code.toString(16)}, '${letters}']`)
  return [
    '/**',
    ' * GENERATED by scripts/generate-glyph-letters.mjs from scripts/unicode/latin-letter-names.txt: do not edit.',
    ' * The symbols drawn as a Latin letter that have no decomposition, as runs of consecutive code points:',
    ' * the first code point of a run and the letters its code points stand for, in order.',
    ' */',
    'export const GLYPH_LETTER_RUNS: ReadonlyArray<readonly [number, string]> = [',
    rows.join(',\n'),
    ']',
    ''
  ].join('\n')
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const source = generate(readFileSync(INPUT, 'utf8'))
  if (process.argv.includes('--print')) process.stdout.write(source)
  else writeFileSync(OUTPUT, source)
}
